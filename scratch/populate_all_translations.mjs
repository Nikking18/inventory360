// Now loop through all 11 languages and update lib/i18n.ts
const allTargetLangs = ['en', 'es', 'fr', 'de', 'hi', 'ja', 'zh', 'ar', 'pt', 'it', 'ru'];

for (const lang of allTargetLangs) {
  const dictionary = fullDictionaryByLang[lang] || localizedEquivalents[lang] || fullDictionaryByLang['en'];
  const langKey = `${lang}: {`;
  const langIndex = code.indexOf(langKey);
  if (langIndex === -1) {
    console.error(`Language block for ${lang} not found`);
    continue;
  }

  const nextLangIndex = code.indexOf(`\n  },`, langIndex);
  if (nextLangIndex === -1) {
    console.error(`Could not find closing brace for ${lang}`);
    continue;
  }

  const currentBlock = code.slice(langIndex, nextLangIndex);
  let additions = '\n';

  for (const [k, v] of Object.entries(dictionary)) {
    if (!currentBlock.includes(`    '${k}':`) && !currentBlock.includes(`    "${k}":`) && !currentBlock.includes(`    ${k}:`)) {
      additions += `    ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
    }
  }

  if (additions.length > 2) {
    code = code.slice(0, nextLangIndex) + additions.slice(0, -1) + code.slice(nextLangIndex);
  }
}

fs.writeFileSync(i18nPath, code, 'utf8');
